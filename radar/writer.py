from radar.models import Item

STYLE_GUIDE = (
    "Ты ведёшь Telegram-канал в стиле degen-качалки: пацаны живут залом, "
    "любят мемы и чёрный юмор про массу, тренировки, читмилы, сушку, "
    "«натти или юзер», эго-лифтинг.\n"
    "Голос: коротко, дерзко, разговорно, с иронией и сарказмом. Сленг зала и "
    "интернет-сленг уместен (масса, сухой, натти, база, банка, дроп, фуллбоди, "
    "рост). Без занудства, канцелярита и академичности. Эмодзи в меру.\n"
    "Формат: цепляющий хук первой строкой; 1–3 коротких абзаца/строки; "
    "концовка — подъёб, вопрос или мотивационный пинок. БЕЗ строки «Источник» и "
    "без ссылок внутри текста.\n"
    "Не строй из себя учёного. Факт из исследования подавай по-простому "
    "(«пацаны в лабе выяснили, что…»).\n"
    "Не выдумывай конкретные цифры, которых нет в материале."
)


def build_rank_prompt(candidates: list[Item], n: int) -> str:
    lines = [
        f"{i}. [{it.source}] {it.title} — {it.text[:200]}"
        for i, it in enumerate(candidates)
    ]
    body = "\n".join(lines)
    return (
        "Ниже кандидаты для постов degen-канала про качалку / силовые / "
        "бодибилдинг.\n\n"
        f"{body}\n\n"
        f"Отбери {n} самых сочных для аудитории качков: дерзкое, практичное, "
        "спорное, мемное — что вызовет реакцию. Скучную академщину опускай. "
        'Верни СТРОГО JSON-массив объектов {"id": <число>, '
        '"reason": "<кратко по-русски>"} без markdown.'
    )


def build_draft_prompt(item: Item, style_guide: str, examples: list[str] | None = None) -> str:
    ex = ""
    if examples:
        joined = "\n".join(f"- {t}" for t in examples if t)
        if joined:
            ex = (
                "\nПримеры заголовков НАШЕГО канала — держи их вайб и тон:\n"
                f"{joined}\n"
            )
    return (
        f"{style_guide}\n{ex}\n"
        "Напиши готовый пост для Telegram на основе материала ниже.\n"
        f"Заголовок материала: {item.title}\n"
        f"Текст материала: {item.text[:1500]}\n\n"
        'Верни СТРОГО JSON-объект {"text": "<готовый пост с переносами строк>", '
        '"alt_titles": ["<вариант 1>", "<вариант 2>"]} без markdown.'
    )
